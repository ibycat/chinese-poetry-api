def _expand(group, dim):
    lex = {}
    for tag, kws in group.items():
        for kw, w in kws.items():
            lex.setdefault(kw, []).append((dim, tag, w))
    return lex


def build_lex():
    lex = {}
    for dim, group in (("theme", THEME), ("style", STYLE), ("mood", MOOD), ("scene", SCENE)):
        for kw, contribs in _expand(group, dim).items():
            lex.setdefault(kw, []).extend(contribs)
    # 同名词去重（保最大权重）
    out = {}
    for kw, cs in lex.items():
        best = {}
        for dim, tag, w in cs:
            k = (dim, tag)
            best[k] = max(best.get(k, 0), w)
        out[kw] = [(d, t, w) for (d, t), w in best.items()]
    return out


LEX = build_lex()


